"""Read executed test outcomes independently of console formatting or exit status."""

from __future__ import annotations

from dataclasses import asdict, dataclass
from pathlib import Path
from xml.etree import ElementTree


@dataclass(frozen=True, slots=True)
class TestResults:
    passed: int
    failed: int
    errors: int
    skipped: int

    @property
    def ready(self) -> bool:
        return self.passed > 0 and self.failed == self.errors == self.skipped == 0

    def as_dict(self) -> dict[str, int]:
        return asdict(self)


def read_junit(path: Path) -> TestResults:
    """Require real testcase outcomes; a zero-exit collection run is insufficient.

    This reads reports generated by our pytest subprocess, not uploaded XML.
    Count leaf cases rather than summing nested suite attributes twice.
    Expected failures are skipped in pytest's JUnit format and do not establish
    readiness of the required suite.
    """
    if not path.is_file() or path.is_symlink() or path.stat().st_size > 16 * 1024 * 1024:
        raise ValueError("missing, unsafe or oversized pytest JUnit report")
    try:
        root = ElementTree.fromstring(path.read_bytes())
    except (OSError, ElementTree.ParseError) as error:
        raise ValueError("invalid pytest JUnit report") from error
    if root.tag not in {"testsuites", "testsuite"}:
        raise ValueError("expected a JUnit test suite")

    def count(suite: ElementTree.Element) -> dict[str, int]:
        totals = dict.fromkeys(("passed", "failed", "errors", "skipped"), 0)
        for case in suite.iter("testcase"):
            if case.find("error") is not None:
                outcome = "errors"
            elif case.find("failure") is not None:
                outcome = "failed"
            elif case.find("skipped") is not None:
                outcome = "skipped"
            else:
                outcome = "passed"
            totals[outcome] += 1
        return totals

    totals = count(root)
    for suite in root.iter():
        if suite.tag not in {"testsuite", "testsuites"}:
            continue
        actual = count(suite)
        declared = {
            "tests": sum(actual.values()),
            "failures": actual["failed"],
            "errors": actual["errors"],
            "skipped": actual["skipped"],
        }
        for field, expected in declared.items():
            if field in suite.attrib and suite.attrib[field] != str(expected):
                raise ValueError("JUnit summary does not match executed testcase outcomes")
    return TestResults(**totals)
